using BenchmarkDotNet.Attributes;
using Networker.ControlPlane.Reports.Documents;

namespace Networker.Benchmarks;

/// <summary>
/// One benchmark per export format over the same representative document —
/// sized like a real integrated report (KPIs, verdict callout, several tables,
/// prose). The document is built once; each benchmark measures Render only.
/// Cross-format numbers are expected to differ wildly (PDF does full layout,
/// Markdown is string concat) — the value is each format's OWN trend, not the
/// race between them.
/// </summary>
[MemoryDiagnoser]
public class ReportExportBenchmarks
{
    private readonly ReportDocument _doc = RepresentativeDocument.Build();
    private readonly MarkdownReportExporter _md = new();
    private readonly HtmlReportExporter _html = new();
    private readonly DocxReportExporter _docx = new();
    private readonly PdfReportExporter _pdf = new();

    [Benchmark]
    public byte[] Markdown() => _md.Render(_doc);

    [Benchmark]
    public byte[] Html() => _html.Render(_doc);

    [Benchmark]
    public byte[] Docx() => _docx.Render(_doc);

    [Benchmark]
    public byte[] Pdf() => _pdf.Render(_doc);
}

/// <summary>
/// A deterministic report shaped like production output: header chips, a KPI
/// strip, a verdict callout, a 30-row protocol table, a 50-row runs table and
/// closing prose. No randomness — identical bytes every run, so allocation
/// numbers are comparable across machines and weeks.
/// </summary>
internal static class RepresentativeDocument
{
    public static ReportDocument Build()
    {
        var protocolRows = new List<IReadOnlyList<string>>();
        for (var i = 0; i < 30; i++)
        {
            protocolRows.Add(
            [
                $"http{1 + (i % 3)}",
                $"{10 + i}",
                $"{12.5 + i * 0.7:0.0} ms",
                $"{40.0 + i * 1.3:0.0} ms",
                $"{95.0 + i * 2.1:0.0} ms",
                i % 7 == 0 ? "1" : "0",
            ]);
        }

        var runRows = new List<IReadOnlyList<string>>();
        for (var i = 0; i < 50; i++)
        {
            runRows.Add(
            [
                $"run-{i:d4}",
                "completed",
                $"{200 + i * 3}",
                $"{198 + i * 3}",
                $"2026-08-{1 + (i % 28):d2} 06:{i % 60:d2}Z",
            ]);
        }

        return new ReportDocument(
            Title: "Integrated Test Report",
            Subtitle: "benchmark fixture — deterministic representative content",
            GeneratedAt: new DateTime(2026, 8, 7, 12, 0, 0, DateTimeKind.Utc),
            Meta:
            [
                new ReportMeta("Project", "Pre-Prod Testing"),
                new ReportMeta("Target", "example.com:443"),
                new ReportMeta("Window", "last 30 days"),
                new ReportMeta("Runs", "50"),
            ],
            Sections:
            [
                new ReportSection(
                    "Executive summary",
                    new MetricsBlock(
                        new Metric("Success rate", "99.2%", ReportTone.Good),
                        new Metric("p50 latency", "42.3 ms", ReportTone.Neutral),
                        new Metric("p95 latency", "128.7 ms", ReportTone.Warn),
                        new Metric("Failed runs", "3", ReportTone.Bad)),
                    new CalloutBlock(
                        "Network path healthy; upload direction is network-bound at 96% of the measured ceiling.",
                        ReportTone.Good),
                    new ProseBlock(
                        "Fifty runs across three protocols in the reporting window. "
                        + "Latency distributions are stable; the two regressions trace "
                        + "to a single provider incident on 08-03.")),
                new ReportSection(
                    "Per-protocol results",
                    new TableBlock(
                        Headers: ["Mode", "Attempts", "p50", "p95", "p99", "Failures"],
                        Rows: protocolRows,
                        Aligns:
                        [
                            ColumnAlign.Left,
                            ColumnAlign.Right,
                            ColumnAlign.Right,
                            ColumnAlign.Right,
                            ColumnAlign.Right,
                            ColumnAlign.Right,
                        ])),
                new ReportSection(
                    "Recent runs",
                    new TableBlock(
                        Headers: ["Run", "Status", "Attempts", "OK", "Started"],
                        Rows: runRows),
                    new ProseBlock(
                        "Full attempt-level detail is available per run in the dashboard.")),
            ],
            FooterNote: "Generated by the Networker.Benchmarks fixture — content is synthetic.");
    }
}
