    public static IEnumerable<object[]> Exporters()
    {
        yield return new object[] { new MarkdownReportExporter() };
        yield return new object[] { new HtmlReportExporter() };
        yield return new object[] { new DocxReportExporter() };
        yield return new object[] { new PdfReportExporter() };
    }

    [Theory]
    [MemberData(nameof(Exporters))]
    public void Exporter_produces_nonempty_output_with_sane_metadata(IReportExporter exporter)
    {
        var bytes = exporter.Render(SampleDoc());

        Assert.NotEmpty(bytes);
        Assert.False(string.IsNullOrWhiteSpace(exporter.ContentType));
        Assert.Matches("^[a-z0-9]+$", exporter.FileExtension);

        WriteSmokeArtifact(exporter, bytes);
    }

    [Fact]
