    [Fact]
    public void Resolver_returns_available_formats_and_rejects_unregistered()
    {
        var resolver = new ReportExporterResolver(new IReportExporter[]
        {
            new MarkdownReportExporter(), new HtmlReportExporter(), new DocxReportExporter(),
        });

        Assert.True(resolver.TryResolve(ReportFormat.Markdown, out _));
        Assert.False(resolver.TryResolve(ReportFormat.Pdf, out _));   // not registered in PR1
        Assert.Equal(new[] { "docx", "html", "markdown" }, resolver.AvailableDocumentFormats);
    }

