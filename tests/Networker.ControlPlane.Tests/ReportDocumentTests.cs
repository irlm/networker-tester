    // ── helpers ────────────────────────────────────────────────────────────────

    private static AttemptView Attempt(
        int seq, string protocol, bool success, string? error = null, AttemptHttpView? http = null) =>
        new(Guid.NewGuid(), protocol, seq,
            new DateTime(2026, 7, 28, 14, 0, seq, DateTimeKind.Utc),
            new DateTime(2026, 7, 28, 14, 0, seq, DateTimeKind.Utc).AddMilliseconds(100),
            success, error, 0, Http: http);

    private static void WriteSmokeArtifact(IReportExporter exporter, byte[] bytes)
    {
        var dir = Environment.GetEnvironmentVariable("REPORT_SMOKE_DIR");
        if (string.IsNullOrWhiteSpace(dir))
        {
            return;
        }
        Directory.CreateDirectory(dir);
        File.WriteAllBytes(Path.Combine(dir, $"sample.{exporter.FileExtension}"), bytes);
    }
