    [Fact]
    public void RunReport_builds_summary_protocol_and_attempts()
    {
        var attempts = new[]
        {
            Attempt(1, "http2", true, http: new AttemptHttpView(200, "HTTP/2", 40, 98, 1024, 0, null, null)),
            Attempt(2, "http2", true, http: new AttemptHttpView(200, "HTTP/2", 44, 110, 1024, 0, null, null)),
            Attempt(3, "http3", false, error: "connection timed out"),
        };
        var input = new RunReportInput(
            Guid.NewGuid(), "acme", "prod-sweep", "api.acme.com", "completed",
            new DateTime(2026, 7, 28, 14, 0, 0, DateTimeKind.Utc),
            new DateTime(2026, 7, 28, 14, 0, 12, DateTimeKind.Utc),
            SuccessCount: 2, FailureCount: 1, ErrorMessage: null, Attempts: attempts);

        var doc = RunReportDocument.Build(input);

        Assert.Equal("Test Run Report", doc.Title);
        Assert.Contains(doc.Sections, s => s.Heading == "Latency by protocol");
        Assert.Contains(doc.Sections, s => s.Heading == "Attempts");
        // The failed attempt's error surfaces in the rendered markdown.
        var md = Encoding.UTF8.GetString(new MarkdownReportExporter().Render(doc));
        Assert.Contains("connection timed out", md);
        Assert.Contains("1 of 3 attempts failed.", md);
    }

