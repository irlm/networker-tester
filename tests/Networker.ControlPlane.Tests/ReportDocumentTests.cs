    [Fact]
    public void Html_is_self_contained_with_inline_logo_and_escaping()
    {
        var html = Encoding.UTF8.GetString(new HtmlReportExporter().Render(SampleDoc()));

        Assert.StartsWith("<!doctype html>", html);
        Assert.Contains("<svg", html);                    // inline wordmark
        Assert.Contains("#863bff", html);                 // brand purple in CSS
        // Self-contained: no external stylesheet/script/font/image fetches.
        // (The SVG's xmlns="http://www.w3.org/2000/svg" is a namespace, not a request.)
        Assert.DoesNotContain("<link", html);
        Assert.DoesNotContain("<script", html);
        Assert.DoesNotContain("src=\"http", html);
        Assert.DoesNotContain("@import", html);
        Assert.Contains("<table>", html);
    }

